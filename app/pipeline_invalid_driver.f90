program pipeline_invalid_driver
  use sklearn_pipeline
  use sklearn_preprocessing, only: standard_scaler,simple_imputer
  use sklearn_feature_selection, only: select_k_best
  use sklearn_linear_model, only: ridge,logistic_regression
  use sklearn_compose, only: column_transformer
  use sklearn_common, only: dp,require
  use sklearn_feature_extraction, only: feature_string
  use, intrinsic :: ieee_arithmetic
  implicit none
  type(pipeline) :: model,part
  type(standard_scaler) :: scaler
  type(simple_imputer) :: imputer
  type(select_k_best) :: selection
  type(ridge) :: base
  type(logistic_regression) :: classifier
  type(column_transformer) :: column
  type(feature_string) :: names(2)
  type(feature_string), allocatable :: output(:)
  real(dp) :: x(6,2),y(6),w(6),nan,inf,value
  integer :: classes(6)
  real(dp), allocatable :: v(:),z(:,:)
  integer, allocatable :: labels(:)
  character(64) :: argument
  call get_command_argument(1,argument)
  x=reshape([1._dp,2._dp,3._dp,4._dp,5._dp,6._dp,2._dp,4._dp,1._dp,5._dp,3._dp,7._dp],[6,2])
  y=[1._dp,2._dp,1._dp,2._dp,1._dp,2._dp];w=1;classes=[-2,-2,-2,7,7,7]
  names(1)%text='a';names(2)%text='b';selection%k=1
  nan=ieee_value(0._dp,ieee_quiet_nan);inf=ieee_value(0._dp,ieee_positive_inf)
  allocate(model%steps(2));model%steps(1)%name='scale';allocate(model%steps(1)%model,source=scaler)
  model%steps(2)%name='final';allocate(model%steps(2)%model,source=base)
  select case(trim(argument))
  case('unallocated_steps')
    deallocate(model%steps);call model%fit(x,y)
  case('empty_steps')
    deallocate(model%steps);allocate(model%steps(0));call model%fit(x,y)
  case('unallocated_name')
    deallocate(model%steps(1)%name);call model%fit(x,y)
  case('duplicate_name')
    model%steps(2)%name='scale';call model%fit(x,y)
  case('name_delimiter')
    model%steps(1)%name='bad__name';call model%fit(x,y)
  case('reserved_name')
    model%steps(1)%name='memory';call model%fit(x,y)
  case('action_drop')
    model%steps(1)%action='drop';call model%fit(x,y)
  case('model_unallocated')
    deallocate(model%steps(1)%model);call model%fit(x,y)
  case('intermediate_regressor')
    deallocate(model%steps(1)%model)
    allocate(model%steps(1)%model,source=base);call model%fit(x,y)
  case('unsupported_intermediate')
    deallocate(model%steps(1)%model)
    allocate(model%steps(1)%model,source=1);call model%fit(x,y)
  case('unsupported_final')
    deallocate(model%steps(2)%model)
    allocate(model%steps(2)%model,source=1);call model%fit(x,y)
  case('predict_unfitted')
    v=model%predict(x)
  case('proba_unfitted')
    z=model%predict_proba(x)
  case('names_unfitted')
    output=model%get_feature_names_out()
  case('inverse_unfitted')
    z=model%inverse_transform(x)
  case('transform_estimator')
    call model%fit(x,y);z=model%transform(x)
  case('fit_transform_estimator')
    z=model%fit_transform(x,y)
  case('predict_class_regressor')
    call model%fit(x,y);labels=model%predict_class(x)
  case('predict_classifier')
    call classifier_tail();call model%fit(x,classes);v=model%predict(x)
  case('matrix_predict_classifier')
    call classifier_tail();call model%fit(x,classes)
    z=model%predict_matrix(x)
  case('probability_regressor')
    call model%fit(x,y);z=model%predict_proba(x)
  case('decision_regressor')
    call model%fit(x,y);z=model%decision_function(x)
  case('names_estimator')
    call model%fit(x,y);output=model%get_feature_names_out()
  case('inverse_estimator')
    call model%fit(x,y);z=model%inverse_transform(x)
  case('missing_regression_target')
    call model%fit(x)
  case('missing_classification_target')
    call classifier_tail();call model%fit(x)
  case('nonfinite_target')
    y(1)=nan;call model%fit(x,y)
  case('classifier_nonfinite')
    call classifier_tail();y(1)=nan;call model%fit(x,y)
  case('classifier_continuous')
    call classifier_tail();y(1)=1.1_dp;call model%fit(x,y)
  case('classifier_large')
    call classifier_tail();y(1)=1.e15_dp;call model%fit(x,y)
  case('target_count')
    call model%fit(x,y(:5))
  case('weight_count')
    call model%fit(x,y,w(:5))
  case('weight_nan')
    w(1)=nan;call model%fit(x,y,w)
  case('weight_inf')
    w(1)=inf;call model%fit(x,y,w)
  case('weight_negative')
    w(1)=-1;call model%fit(x,y,w)
  case('zero_weight')
    w=0;call model%fit(x,y,w)
  case('matrix_target_unsupported')
    call model%fit(x,x)
  case('matrix_score_unsupported')
    call model%fit(x,y);value=model%score(x,x)
  case('missing_supervised_target')
    deallocate(model%steps(1)%model)
    allocate(model%steps(1)%model,source=selection);call model%fit(x)
  case('supervised_matrix_target')
    deallocate(model%steps(1)%model)
    allocate(model%steps(1)%model,source=selection);call model%fit(x,x)
  case('feature_name_count')
    call model%fit(x,y,feature_names=names(:1))
  case('feature_name_unallocated')
    deallocate(names(1)%text);call model%fit(x,y,feature_names=names)
  case('output_name_count')
    call transformer_tail();call model%fit(x)
    output=model%get_feature_names_out(names(:1))
  case('output_name_mismatch')
    call transformer_tail();call model%fit(x,names)
    names(1)%text="changed";output=model%get_feature_names_out(names)
  case('output_name_blanks')
    call transformer_tail();call model%fit(x,names)
    names(1)%text="a ";output=model%get_feature_names_out(names)
  case('slice_zero')
    part=model%slice(0,1)
  case('slice_large')
    part=model%slice(1,3)
  case('slice_reverse')
    part=model%slice(2,1)
  case('score_target_count')
    call model%fit(x,y);value=model%score(x,y(:5))
  case('score_weight_count')
    call model%fit(x,y);value=model%score(x,y,w(:5))
  case('score_weight_nan')
    call model%fit(x,y);w(1)=nan;value=model%score(x,y,w)
  case('score_weight_zero')
    call model%fit(x,y);w=0;value=model%score(x,y,w)
  case('transformer_score')
    call transformer_tail();call model%fit(x);value=model%score(x,y)
  case('passthrough_predict')
    model%steps(2)%action="passthrough";call model%fit(x);v=model%predict(x)
  case('passthrough_score')
    model%steps(2)%action="passthrough";call model%fit(x);value=model%score(x,y)
  case('unsupported_inverse')
    deallocate(model%steps(1)%model)
    allocate(model%steps(1)%model,source=imputer)
    call transformer_tail()
    call model%fit(x)
    z=model%inverse_transform(x)
  case('transformer_fit_weights')
    call transformer_tail();call model%fit(x,y,w)
  case('graph_classifier')
    call classifier_tail();allocate(column%transformers(1))
    column%transformers(1)%name="pipe";column%transformers(1)%columns=[1,2]
    allocate(column%transformers(1)%model,source=model);z=column%fit_transform(x)
  case default
    call require(.false.,'unknown invalid case')
  end select
  error stop 'invalid case unexpectedly accepted'
contains
  subroutine classifier_tail()
    deallocate(model%steps(2)%model);allocate(model%steps(2)%model,source=classifier)
  end subroutine
  subroutine transformer_tail()
    deallocate(model%steps(2)%model);allocate(model%steps(2)%model,source=scaler)
  end subroutine
end program
